/**
 * ASTRA Health - Radiation Safety Rules Engine
 * Deterministic, configurable safety protocols based on NASA / NCRP deep space flight standards.
 * 
 * Safety Limits Reference (NASA Standard 3001 / NCRP Report 153):
 * - Nominal deep space cruise daily rate: 0.35 - 0.55 mSv/day (GCR background)
 * - Daily attention threshold: > 1.5 mSv/day (SPE onset or enhanced solar activity)
 * - Daily critical threshold: > 10.0 mSv/day (Active Solar Particle Event)
 * - 30-day limit: 250 mSv (Blood-forming organ protection)
 * - 1-year limit: 500 mSv
 * - Career limit: 600 mSv (Universal standard limit for deep space exploration)
 * 
 * Note: Alerts are generated by deterministic rules, NEVER by unpredictable AI generation.
 */

import { RadiationMeasurement, HealthAlert } from '../types/health';

export interface RadiationSafetyProtocol {
  id: string;
  name: string;
  agency: string;
  nominalDailyRange_mSv: { min: number; max: number };
  dailyThresholds: {
    monitor: number; // mSv/day
    attention: number; // mSv/day
    critical: number; // mSv/day
  };
  monthlyLimit_mSv: number;
  careerLimit_mSv: number;
}

export const ACTIVE_MISSION_RADIATION_PROTOCOL: RadiationSafetyProtocol = {
  id: 'NASA-MARS-01-RAD-STD',
  name: 'NASA Mars-01 Interplanetary Radiation Safety Standard',
  agency: 'NASA / ESA Space Flight Health Directorate',
  nominalDailyRange_mSv: { min: 0.35, max: 0.65 },
  dailyThresholds: {
    monitor: 1.0, // mSv/day
    attention: 2.5, // mSv/day
    critical: 10.0, // mSv/day
  },
  monthlyLimit_mSv: 250,
  careerLimit_mSv: 600,
};

/**
 * Normalizes any radiation measurement into mSv equivalent if physically valid.
 * IMPORTANT: Gy (absorbed dose) and Sv (equivalent dose) are distinct physical quantities.
 * For deep space GCR, the quality factor Q is ~3.0-3.8 depending on heavy ion flux.
 */
export function normalizeToMilliSieverts(
  value: number,
  unit: string,
  measurementType: string,
  estimatedQualityFactor = 3.5
): number | null {
  if (value < 0 || isNaN(value)) return null;

  switch (unit) {
    case 'uSv':
      return value / 1000;
    case 'mSv':
      return value;
    case 'Sv':
      return value * 1000;
    case 'uSv/h':
      return (value * 24) / 1000; // 24h projection
    case 'mSv/h':
      return value * 24; // 24h projection
    case 'uGy':
      // Absorbed dose converted to equivalent dose using quality factor
      return (value * estimatedQualityFactor) / 1000;
    case 'mGy':
      return value * estimatedQualityFactor;
    case 'Gy':
      return value * 1000 * estimatedQualityFactor;
    case 'mGy/h':
      return value * 24 * estimatedQualityFactor;
    default:
      return null;
  }
}

export interface RadiationEvaluationResult {
  severity: 'GREEN' | 'BLUE' | 'YELLOW' | 'ORANGE' | 'RED';
  statusText: 'Stable' | 'Monitor' | 'Attention' | 'Critical';
  alert: HealthAlert | null;
  summary: string;
}

/**
 * Deterministically evaluates a radiation measurement against active mission protocols.
 */
export function evaluateRadiationSafety(
  measurement: RadiationMeasurement,
  cumulative_mSv: number,
  protocol = ACTIVE_MISSION_RADIATION_PROTOCOL
): RadiationEvaluationResult {
  const normVal = measurement.equivalent_mSv ?? normalizeToMilliSieverts(measurement.value, measurement.unit, measurement.measurementType) ?? 0.45;
  const sol = measurement.sol;
  const nowIso = new Date().toISOString();

  // 1. Critical Solar Particle Event / Acute Threshold (> 10 mSv/day)
  if (normVal >= protocol.dailyThresholds.critical) {
    return {
      severity: 'RED',
      statusText: 'Critical',
      summary: `Acute radiation excursion: ${normVal.toFixed(2)} mSv/day (Active SPE protocol required)`,
      alert: {
        id: `alert-rad-crit-${measurement.id}`,
        sol,
        timestamp: nowIso,
        severity: 'RED',
        category: 'RADIATION',
        title: 'CRITICAL RADIATION EXCURSION DETECTED',
        message: `Personal dosimeter recorded an acute exposure rate of ${normVal.toFixed(2)} mSv/day (${measurement.value} ${measurement.unit}), exceeding the mission critical threshold (${protocol.dailyThresholds.critical} mSv/day).`,
        contributingFactors: [
          `Personal dosimeter (${measurement.source}) recorded ${measurement.value} ${measurement.unit}`,
          `Rate equivalent: ${normVal.toFixed(2)} mSv/day`,
          `Mission cumulative exposure: ${(cumulative_mSv + normVal).toFixed(1)} mSv / ${protocol.careerLimit_mSv} mSv limit`,
        ],
        baselineComparison: `Nominal deep space cruise baseline is ${protocol.nominalDailyRange_mSv.min}–${protocol.nominalDailyRange_mSv.max} mSv/day. Excursion is +${Math.round((normVal / protocol.nominalDailyRange_mSv.max) * 100)}% above baseline.`,
        triggerRationale: `Deterministic threshold rule: Recorded daily dose ${normVal.toFixed(2)} mSv >= ${protocol.dailyThresholds.critical} mSv/day.`,
        recommendedNextStep: 'Immediately enter the spacecraft radiation storm shelter (water wall / propellant bay). Verify storm shelter dosimeters and notify Mission Control.',
        source: 'DETERMINISTIC_RULE',
        acknowledged: false,
      },
    };
  }

  // 2. Attention Threshold (> 2.5 mSv/day or career cumulative > 85%)
  const isCareerWarning = (cumulative_mSv + normVal) >= protocol.careerLimit_mSv * 0.85;
  if (normVal >= protocol.dailyThresholds.attention || isCareerWarning) {
    return {
      severity: 'ORANGE',
      statusText: 'Attention',
      summary: `Elevated radiation exposure: ${normVal.toFixed(2)} mSv/day (Attention threshold exceeded)`,
      alert: {
        id: `alert-rad-attn-${measurement.id}`,
        sol,
        timestamp: nowIso,
        severity: 'ORANGE',
        category: 'RADIATION',
        title: 'RADIATION EXPOSURE THRESHOLD ADVISORY',
        message: `A radiation exposure threshold defined by the active mission protocol has been reached. Daily rate: ${normVal.toFixed(2)} mSv/day from ${measurement.source.replace('_', ' ')}.`,
        contributingFactors: [
          `Personal dosimeter recorded ${measurement.value} ${measurement.unit}`,
          `Calculated daily equivalent: ${normVal.toFixed(2)} mSv/day`,
          `Cumulative career progress: ${Math.round(((cumulative_mSv + normVal) / protocol.careerLimit_mSv) * 100)}% of limit`,
        ],
        baselineComparison: `Active rate is ${normVal.toFixed(2)} mSv/day vs nominal baseline ${protocol.nominalDailyRange_mSv.min}–${protocol.nominalDailyRange_mSv.max} mSv/day.`,
        triggerRationale: `Deterministic threshold rule: Exposure ${normVal.toFixed(2)} mSv >= ${protocol.dailyThresholds.attention} mSv/day.`,
        recommendedNextStep: 'Review radiation dosimeter placement and minimize time in lightly shielded habitat modules. Check NASA DONKI space weather updates.',
        source: 'DETERMINISTIC_RULE',
        acknowledged: false,
      },
    };
  }

  // 3. Monitor Threshold (> 1.0 mSv/day)
  if (normVal >= protocol.dailyThresholds.monitor) {
    return {
      severity: 'YELLOW',
      statusText: 'Monitor',
      summary: `Minor radiation rate elevation: ${normVal.toFixed(2)} mSv/day (Monitoring state)`,
      alert: {
        id: `alert-rad-mon-${measurement.id}`,
        sol,
        timestamp: nowIso,
        severity: 'YELLOW',
        category: 'RADIATION',
        title: 'RADIATION RATE MONITORING',
        message: `Personal exposure rate slightly elevated to ${normVal.toFixed(2)} mSv/day. Standard operational monitoring recommended.`,
        contributingFactors: [
          `Personal dosimeter (${measurement.source}) recorded ${measurement.value} ${measurement.unit}`,
          `Calculated equivalent: ${normVal.toFixed(2)} mSv/day`,
        ],
        baselineComparison: `Baseline: ${protocol.nominalDailyRange_mSv.min}–${protocol.nominalDailyRange_mSv.max} mSv/day (Current: ${normVal.toFixed(2)} mSv/day).`,
        triggerRationale: `Deterministic threshold rule: Exposure ${normVal.toFixed(2)} mSv >= ${protocol.dailyThresholds.monitor} mSv/day.`,
        recommendedNextStep: 'Log secondary dosimeter measurement and monitor cabin shielding configuration.',
        source: 'DETERMINISTIC_RULE',
        acknowledged: false,
      },
    };
  }

  // 4. Nominal Stable State
  return {
    severity: 'GREEN',
    statusText: 'Stable',
    summary: `Nominal deep space cruise exposure: ${normVal.toFixed(2)} mSv/day`,
    alert: null,
  };
}
